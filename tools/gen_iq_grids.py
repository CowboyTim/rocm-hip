#!/usr/bin/env python3
# gen_iq_grids.py -- extract the IQ1 / IQ2 / IQ3 codebooks from ggml's ggml-common.h into src/iq_grids.h
#
#   gen_iq_grids.py <ggml-common.h> > src/iq_grids.h
#
# The tables are ggml's (MIT License, Copyright (c) 2023-2026 The ggml authors), copied verbatim; the includer
# defines IQ_TABLE(type, name, size) (static const on the CPU, __constant__ on the GPU) before including.

import re, sys

NAMES = ["ksigns_iq2xs", "iq2xxs_grid", "iq2xs_grid", "iq2s_grid", "iq3xxs_grid", "iq3s_grid", "iq1s_grid"]


def main():
    src = open(sys.argv[1]).read()
    out = ["// iq_grids.h -- generated by tools/gen_iq_grids.py from ggml's ggml-common.h: do not edit.",
           "// The codebooks of the IQ1_S / IQ1_M, IQ2_XXS / IQ2_XS / IQ2_S and IQ3_XXS / IQ3_S quantizations and their",
           "// sign table, copied verbatim from ggml (MIT License, Copyright (c) 2023-2026 The ggml authors).",
           "// Define IQ_TABLE(type, name, size) before including.",
           "#pragma once", ""]
    for name in NAMES:
        m = re.search(r"GGML_TABLE_BEGIN\((\w+),\s*" + name + r",\s*(\w+)\)\n(.*?)GGML_TABLE_END\(\)", src, re.S)
        if not m:
            sys.exit(f"{name}: not found")
        typ, size, body = m.group(1), m.group(2), m.group(3)
        if size == "NGRID_IQ1S":
            size = "2048"
        out.append(f"IQ_TABLE({typ}, {name}, {size}) = {{")
        out.append(body.rstrip())
        out.append("};")
        out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
