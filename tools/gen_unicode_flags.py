#!/usr/bin/env python3
"""Generate src/unicode_flags.inc from llama.cpp's src/unicode-data.cpp (MIT).

The tokenizer's pre-tokenizers need Unicode general-category flags (letter, number, mark, ...) and the
whitespace set, exactly as the reference tokenizer sees them, so the table is copied from the reference
rather than rebuilt from Python's unicodedata (whose Unicode version may differ).

    tools/gen_unicode_flags.py llama.cpp/src/unicode-data.cpp > src/unicode_flags.inc
"""

import re
import sys


def block(src, name):
    start = src.index(name)
    body = src[src.index("{", start) + 1:]
    return body[:body.index("};")]


def main():
    src = open(sys.argv[1]).read()
    ranges = re.findall(r"\{0x([0-9A-Fa-f]+),\s*0x([0-9A-Fa-f]+)\}", block(src, "unicode_ranges_flags"))
    spaces = re.findall(r"0x([0-9A-Fa-f]+)", block(src, "unicode_set_whitespace"))
    assert ranges and int(ranges[0][0], 16) == 0 and int(ranges[-1][0], 16) == 0x110000, "unexpected ranges"
    out = sys.stdout
    out.write("// Generated by tools/gen_unicode_flags.py from llama.cpp src/unicode-data.cpp (MIT). Do not edit.\n")
    out.write("// UNICODE_RANGES: {first codepoint, category flags}; a range ends where the next one starts.\n")
    out.write("// UNICODE_WHITESPACE: codepoints matched by \\s.\n\n")
    out.write("static const struct { uint32_t start; uint16_t flags; } UNICODE_RANGES[] = {\n")
    for i in range(0, len(ranges), 4):
        out.write("   " + "".join(" {0x%06X, 0x%04X}," % (int(a, 16), int(b, 16)) for a, b in ranges[i:i + 4]) + "\n")
    out.write("};\n\nstatic const uint32_t UNICODE_WHITESPACE[] = {\n")
    for i in range(0, len(spaces), 8):
        out.write("   " + "".join(" 0x%06X," % int(c, 16) for c in spaces[i:i + 8]) + "\n")
    out.write("};\n")


if __name__ == "__main__":
    main()
